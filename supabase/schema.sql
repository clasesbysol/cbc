-- CBC x SOLved · esquema canónico de acceso granular
-- Aplicar en Supabase después de revisar contra la base real. max_unit se conserva sólo por compatibilidad.
create table if not exists public.access_profiles (
  email text primary key,
  max_unit integer not null default 1 check (max_unit between 1 and 13),
  active boolean not null default true,
  role text not null default 'student' check (role in ('student','tester','admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  access_starts_at timestamptz not null default now(),
  access_expires_at timestamptz
);
alter table public.access_profiles add column if not exists access_starts_at timestamptz not null default now();
alter table public.access_profiles add column if not exists access_expires_at timestamptz;
create table if not exists public.access_grants (
  email text not null references public.access_profiles(email) on update cascade on delete cascade,
  subject text not null default 'chemistry',
  unit_no integer not null check (unit_no between 1 and 13),
  grant_type text not null check (grant_type in ('unit','chapter','guide','practice','evaluation','partial','resource')),
  grant_key text not null default '*',
  created_at timestamptz not null default now(),
  primary key (email,subject,unit_no,grant_type,grant_key)
);
create table if not exists public.course_sections (
  id bigint generated by default as identity primary key,
  subject text not null, unit_no integer not null check (unit_no between 1 and 13),
  section_key text not null, section_type text not null, title text not null,
  sort_order integer not null default 0, body_html text not null default '',
  is_public boolean not null default false, created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(), unique(subject,unit_no,section_key)
);
alter table public.access_profiles enable row level security;
alter table public.access_grants enable row level security;
alter table public.course_sections enable row level security;
create or replace function public.is_cbc_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select lower(coalesce(auth.jwt()->>'email',''))='clasesbysol@gmail.com' $$;
create or replace function public.has_active_cbc_access(target_subject text,target_unit integer,target_type text,target_key text)
returns boolean language sql stable security definer set search_path=public
as $$
  select public.is_cbc_admin() or exists(
    select 1 from public.access_profiles p join public.access_grants g on lower(g.email)=lower(p.email)
    where lower(p.email)=lower(coalesce(auth.jwt()->>'email','')) and p.active
      and now()>=p.access_starts_at and (p.access_expires_at is null or now()<=p.access_expires_at)
      and g.subject=target_subject and g.unit_no=target_unit
      and ((g.grant_type='unit' and g.grant_key='*') or (g.grant_type=target_type and g.grant_key=target_key))
  )
$$;
